#!/usr/bin/env bash
# Runs every formatter, analyzer, test suite and build for Brickfolk and stores
# the logs under the clone-this run directory (evidence/quality). Also writes
# the rebrand / secret / asset scans the audits reference. Fails on the first
# failing command so partial evidence is never mistaken for a pass.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
run_dir="$root/.devin/clone-this/brickfolk"
q="$run_dir/evidence/quality"
mkdir -p "$q"
cd "$root"

step() {
  local name="$1"; shift
  echo "==> $name: $*"
  local status=0
  "$@" > "$q/$name.log" 2>&1 || status=$?
  cat "$q/$name.log"
  echo "exit=$status" >> "$q/$name.log"
  [ "$status" -eq 0 ] || { echo "FAILED: $name" >&2; exit 1; }
}

step pub-get bash -c '(cd shared && dart pub get) && (cd server && dart pub get) && (cd app && flutter pub get)'
step format bash -c 'cd app && dart format --set-exit-if-changed . && cd ../server && dart format --set-exit-if-changed . && cd ../shared && dart format --set-exit-if-changed .'
step analyze bash -c 'cd app && flutter analyze && cd ../server && dart analyze --fatal-infos && cd ../shared && dart analyze --fatal-infos'
step node-check bash -c 'node --check test/e2e/run.mjs && node --check test/e2e/review_video.mjs && cd test/e2e && npm ls --depth=0'
step python-check bash -c 'python3 -B -m py_compile test/e2e/visual_compare.py test/manifest/build_manifest.py test/manifest/sweep.py && echo compiled'
step shared-test bash -c 'cd shared && dart test'
step server-test bash -c 'cd server && dart test'
step app-test bash -c 'cd app && flutter test'
step pub-outdated bash -c 'cd app && flutter pub outdated || true; cd ../server && dart pub outdated || true'

# Scans referenced by the rebrand and security audits.
{
  echo "# Rebrand scan: source-brand terms in shipped code, docs and assets"
  echo "# (matches outside the reference notes are listed; expected: only the honest"
  echo "#  reference-boundary statements in README.md and PROTOCOL.md)"
  grep -rniE 'roblox|robux|builderman|\bnoob\b|bloxburg|\boof\b' \
    --include='*.dart' --include='*.md' --include='*.yaml' --include='*.json' --include='*.html' \
    --include='*.mjs' --include='*.py' --include='*.sh' --include='*.plist' --include='*.xml' \
    --include='*.gradle' --include='*.kts' --include='*.swift' \
    --exclude-dir=.devin --exclude-dir=build --exclude-dir=node_modules --exclude-dir=.dart_tool \
    . 2>/dev/null || echo "(no matches)"
} > "$q/rebrand-scan.txt"

{
  echo "# Secret scan: credential-shaped strings in tracked source"
  git -C "$root" ls-files --cached --others --exclude-standard . | grep -v '^.devin/' | \
    xargs grep -nE '(AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY|ghp_[A-Za-z0-9]{20,}|xox[baprs]-[A-Za-z0-9-]{10,}|api[_-]?key\s*[:=]\s*["'"'"'][A-Za-z0-9]{16,})' \
    || echo "(no matches)"
  echo
  echo "# Tracked env / credential files"
  git -C "$root" ls-files --cached --others --exclude-standard . | grep -E '(^|/)\.env|credentials|\.pem$|\.p12$|keystore' || echo "(none)"
} > "$q/secret-scan.txt"

{
  echo "# Asset inventory (everything shipped under app/assets and platform icons)"
  find app/assets -type f | sort
  echo
  echo "# Licence"
  head -5 app/assets/fonts/LICENSE-Inter.txt
  echo
  echo "# Platform icons are generated by tool/make_icons.py from the Brickfolk brick"
  echo "# mark (see rebrand audit); no third-party art is bundled."
  find app/ios/Runner/Assets.xcassets app/macos/Runner/Assets.xcassets app/android/app/src/main/res app/web -type f \( -name '*.png' -o -name '*.ico' \) | sort
} > "$q/asset-inventory.txt"

# Fingerprint coverage listing for the reliability audit (which files the
# clone-this revision hashes). The skill directory can be overridden with
# CLONE_THIS_SKILL_DIR when the plugin is installed elsewhere.
skill_dir="${CLONE_THIS_SKILL_DIR:-$(ls -d "$HOME"/.devin/plugins/cache/github.com_dabit3_clone-this-*/*/.devin/skills/clone-this 2>/dev/null | tail -1)}"
if [ -f "$skill_dir/scripts/fingerprint.py" ]; then
  python3 -B "$skill_dir/scripts/fingerprint.py" "$root" --list > "$q/fingerprint-list.txt"
  echo "fingerprint covers $(grep -c . "$q/fingerprint-list.txt") entries"
else
  echo "clone-this skill not found; set CLONE_THIS_SKILL_DIR" >&2
  exit 1
fi

echo "quality evidence written to $q"
